/*
==============================================================================
Model: sales_by_region.sql
Layer: Marts / Analytical Layer (Table)
Source: ref('stg_orders')
Target: analytics_retail.sales_by_region

Purpose:
  Aggregates transactional performance metrics by sales territory to evaluate
  geographic revenue share and regional customer demand.

Output Metrics:
  - region: Geographic territory (North, South, East, West, Central)
  - total_orders: Count of unique transactions within the region
  - total_quantity: Cumulative units shipped to the region
  - total_revenue: Cumulative revenue generated by the region in INR
==============================================================================
*/

WITH staging_orders AS (
    SELECT *
    FROM {{ ref('stg_orders') }}
)

SELECT
    region,
    COUNT(DISTINCT order_id) AS total_orders,
    SUM(quantity) AS total_quantity,
    ROUND(SUM(revenue), 2) AS total_revenue
FROM staging_orders
GROUP BY
    region
ORDER BY
    total_revenue DESC

